const ACC = { 'É': ['E', 'acute'], 'È': ['E', 'grave'], 'Ê': ['E', 'circ'], 'À': ['A', 'grave'], 'Â': ['A', 'circ'], 'Ç': ['C', 'cedil'], 'Ô': ['O', 'circ'], 'Û': ['U', 'circ'], 'Î': ['I', 'circ'], 'Ù': ['U', 'grave'] };

export function textWidth(str) { return Math.max(0, str.length * 4 - 1); }

/** Écrit un texte en majuscules dans un tampon Px à (x, y) (haut-gauche de la ligne de capitales). */
export function drawText(px, str, x, y, color, shadow = null) {
  const s = String(str).toUpperCase();
  let cx = x;
  for (const ch0 of s) {
    let ch = ch0, acc = null;
    if (ACC[ch0]) [ch, acc] = ACC[ch0];
    const g = G[ch] || G[' '];
    for (let j = 0; j < 5; j++) for (let i = 0; i < 3; i++) if (g[j][i] === '1') {
      if (shadow) px.set(cx + i + 1, y + j + 1, shadow);
      px.set(cx + i, y + j, color);
    }
    if (acc === 'acute') { px.set(cx + 2, y - 2, color); px.set(cx + 1, y - 1, color); }
    if (acc === 'grave') { px.set(cx, y - 2, color); px.set(cx + 1, y - 1, color); }
    if (acc === 'circ') { px.set(cx + 1, y - 2, color); px.set(cx, y - 1, color); px.set(cx + 2, y - 1, color); }
    if (acc === 'cedil') { px.set(cx + 1, y + 5, color); px.set(cx, y + 6, color); }
    cx += 4;
  }
  return cx - x;
}

